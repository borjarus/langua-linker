fn main() {
    // App variant set by frontend/scripts/tauri-variant.mjs. Unset (plain cargo/IDE builds) means
    // dev, so a release build is always an explicit choice.
    println!("cargo:rerun-if-env-changed=LL_APP_VARIANT");
    let variant = std::env::var("LL_APP_VARIANT").unwrap_or_else(|_| "dev".to_owned());
    assert!(
        matches!(variant.as_str(), "dev" | "beta" | "release"),
        "unknown LL_APP_VARIANT \"{variant}\" (expected dev|beta|release)"
    );
    println!("cargo:rustc-env=LL_APP_VARIANT={variant}");

    embed_content_password();

    // Declaring app commands makes them subject to capabilities: each one needs an explicit
    // `allow-<command>` permission (generated into permissions/autogenerated). Every command of
    // the frozen contract catalogue is declared (integration checklist rule 1), plus the
    // dev-only diagnostics probes.
    let mut attributes = tauri_build::Attributes::new()
        .app_manifest(tauri_build::AppManifest::new().commands(app_commands()));

    // Tauri needs Common Controls v6 on Windows. tauri-build embeds that manifest only into the
    // app binary, so test executables crash with STATUS_ENTRYPOINT_NOT_FOUND. Embed it for every
    // linked target instead — only when the *target* is Windows MSVC, never for Android/iOS.
    let windows_msvc = std::env::var("CARGO_CFG_TARGET_OS").as_deref() == Ok("windows")
        && std::env::var("CARGO_CFG_TARGET_ENV").as_deref() == Ok("msvc");
    if windows_msvc {
        attributes = attributes
            .windows_attributes(tauri_build::WindowsAttributes::new_without_app_manifest());
        let manifest = std::path::Path::new(&std::env::var("CARGO_MANIFEST_DIR").unwrap())
            .join("windows-app-manifest.xml");
        println!("cargo:rerun-if-changed={}", manifest.display());
        println!("cargo:rustc-link-arg=/MANIFEST:EMBED");
        println!("cargo:rustc-link-arg=/MANIFESTINPUT:{}", manifest.display());
    }

    tauri_build::try_build(attributes).expect("failed to run tauri-build");
}

/// The bundled content (`content/decks/decks.7z`) is encrypted; the app decrypts it at runtime
/// with the password compiled in here, taken from `LANGUA_DECKS_PASSWORD` or the repository `.env`.
fn embed_content_password() {
    const VAR: &str = "LANGUA_DECKS_PASSWORD";
    println!("cargo:rerun-if-env-changed={VAR}");
    println!("cargo:rerun-if-changed=../content/decks/decks.7z");
    let dotenv = std::path::Path::new("../.env");
    if dotenv.is_file() {
        println!("cargo:rerun-if-changed=../.env");
    }
    let password = std::env::var(VAR)
        .ok()
        .filter(|value| !value.is_empty())
        .or_else(|| {
            let text = std::fs::read_to_string(dotenv).ok()?;
            text.lines().find_map(|line| {
                let line = line.trim();
                let (name, value) = line.strip_prefix("export ").unwrap_or(line).split_once('=')?;
                let value = value.trim().trim_matches(|c| matches!(c, '"' | '\''));
                (name.trim() == VAR && !value.is_empty()).then(|| value.to_owned())
            })
        })
        .unwrap_or_else(|| {
            panic!("{VAR} is not set: put it in .env (repository root) or the environment — it decrypts content/decks/decks.7z")
        });
    println!("cargo:rustc-env={VAR}={password}");
}

const DIAGNOSTICS_COMMANDS: [&str; 3] =
    ["probe_secret_store", "probe_file_open", "probe_file_save"];

fn app_commands() -> &'static [&'static str] {
    let path = "../crates/contracts/v1/catalogue.json";
    println!("cargo:rerun-if-changed={path}");
    let text = std::fs::read_to_string(path).expect("contract catalogue");
    let catalogue: serde_json::Value = serde_json::from_str(&text).expect("catalogue is JSON");
    let mut commands: Vec<&'static str> = catalogue["operations"]
        .as_object()
        .expect("operations")
        .values()
        .filter(|spec| spec["kind"] != "subscription")
        .map(|spec| -> &'static str {
            Box::leak(
                spec["command"]
                    .as_str()
                    .expect("command")
                    .to_owned()
                    .into_boxed_str(),
            )
        })
        .collect();
    commands.extend(DIAGNOSTICS_COMMANDS);
    Box::leak(commands.into_boxed_slice())
}
